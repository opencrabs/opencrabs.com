#!/usr/bin/env python3
"""Prove the committed docs book was built from the committed sources.

The deploy ships whatever `docs/book` holds. mdbook writes that directory from
`docs/src` plus the locale catalogs in `docs/po`, so a source edit that lands
without a rebuild ships the previous book: old canonicals, old hreflang sets and
an old sitemap, all of which look fine on the page and cost search visibility in
silence. Nothing else in the pipeline notices, because a stale book is still a
well formed one.

This script closes that hole without needing a browser or an mdbook install on
the machine that deploys. It hashes every input that changes the built book and
records the result next to the book, in `docs/book-stamp.json`. The deploy
recomputes the same hash and refuses to ship when anything differs, naming the
inputs that moved.

Usage:
    python3 scripts/book_stamp.py --write   # last step of a book build
    python3 scripts/book_stamp.py --check   # deploy gate, writes nothing
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

DOCS = Path(__file__).resolve().parent.parent
BOOK = DOCS / "book"
STAMP = DOCS / "book-stamp.json"

# Inputs that mdbook reads. Anything under docs/scripts is tooling and does not
# change a page, so editing a helper never fails the gate. messages.pot is the
# template translators fill, not something mdbook consumes, so it is out too.
INPUT_DIRS = ("src", "theme")
INPUT_FILES = ("book.toml",)

# mdbook copies theme assets verbatim, and a directory walk picks up the noise
# an editor or a Python run leaves behind. Neither belongs in a content hash:
# __pycache__ changes on every run and .DS_Store on every Finder visit.
SKIP_DIRS = {"__pycache__"}
SKIP_NAMES = {".DS_Store"}


def inputs() -> list[Path]:
    """Every file whose bytes end up in the built book, sorted for stability."""
    found: list[Path] = []
    for name in INPUT_DIRS:
        root = DOCS / name
        if not root.is_dir():
            continue
        for path in root.rglob("*"):
            if not path.is_file():
                continue
            if any(part in SKIP_DIRS for part in path.parts):
                continue
            if path.name in SKIP_NAMES:
                continue
            found.append(path)
    for name in INPUT_FILES:
        path = DOCS / name
        if path.is_file():
            found.append(path)
    # Catalogs: one per locale, the exact set mdbook-gettext reads.
    found.extend(sorted((DOCS / "po").glob("*.po")))
    return sorted(set(found))


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def collect() -> dict[str, str]:
    return {p.relative_to(DOCS).as_posix(): digest(p) for p in inputs()}


def write() -> int:
    if not (BOOK / "index.html").is_file():
        print(f"book is not built: {BOOK / 'index.html'} is missing", file=sys.stderr)
        return 1
    stamp = {
        "note": "generated by docs/scripts/book_stamp.py --write, do not edit",
        "inputs": collect(),
    }
    STAMP.write_text(
        json.dumps(stamp, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(f"stamp: {len(stamp['inputs'])} inputs recorded in {STAMP.name}")
    return 0


def check() -> int:
    if not (BOOK / "index.html").is_file():
        print(f"book is not built: {BOOK / 'index.html'} is missing", file=sys.stderr)
        return 1
    if not STAMP.is_file():
        print(f"stamp missing: {STAMP}", file=sys.stderr)
        print("run: bash docs/build-all.sh", file=sys.stderr)
        return 1

    try:
        recorded = json.loads(STAMP.read_text(encoding="utf-8"))["inputs"]
    except (ValueError, KeyError) as exc:
        print(f"stamp is unreadable ({exc}), run: bash docs/build-all.sh", file=sys.stderr)
        return 1

    current = collect()
    added = sorted(set(current) - set(recorded))
    removed = sorted(set(recorded) - set(current))
    changed = sorted(p for p in set(current) & set(recorded) if current[p] != recorded[p])

    if not (added or removed or changed):
        print(f"book: current, {len(current)} inputs match {STAMP.name}")
        return 0

    # Name the files, not just the count: whoever hits this needs to know which
    # edit they forgot to build, and the fix is the same command every time.
    for label, paths in (("changed", changed), ("added", added), ("removed", removed)):
        for path in paths[:20]:
            print(f"{label}: {path}", file=sys.stderr)
        if len(paths) > 20:
            print(f"{label}: ... and {len(paths) - 20} more", file=sys.stderr)
    print(
        f"book is stale: {len(changed)} changed, {len(added)} added, "
        f"{len(removed)} removed. Run: bash docs/build-all.sh",
        file=sys.stderr,
    )
    return 1


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Record or verify the sources the committed docs book was built from."
    )
    parser.add_argument("--write", action="store_true", help="write the stamp")
    parser.add_argument("--check", action="store_true", help="verify the stamp")
    args = parser.parse_args()
    if args.write == args.check:
        parser.error("pick exactly one of --write or --check")
    return write() if args.write else check()


if __name__ == "__main__":
    sys.exit(main())
