/// Replace the two generated blocks in a static page. The markers stay put, so
/// the next run finds them again.
pub fn inject_page(page: &str, nav: &str, footer: &str) -> Result<String, String> {
    let page = replace_block(page, NAV_START, NAV_END, nav)?;
    replace_block(&page, FOOTER_START, FOOTER_END, footer)
}

fn replace_block(page: &str, start: &str, end: &str, body: &str) -> Result<String, String> {
    let open = page
        .find(start)
        .ok_or_else(|| format!("missing marker {start}"))?
        + start.len();
    let close = page[open..]
        .find(end)
        .ok_or_else(|| format!("missing marker {end}"))?
        + open;
    let mut out = String::with_capacity(page.len() + body.len());
    out.push_str(&page[..open]);
    out.push('\n');
    out.push_str(body);
    out.push('\n');
    out.push_str(&page[close..]);
    Ok(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn thousands_groups_digits() {
        assert_eq!(thousands(0), "0");
        assert_eq!(thousands(999), "999");
        assert_eq!(thousands(1465), "1,465");
        assert_eq!(thousands(1_234_567), "1,234,567");
    }

    #[test]
    fn nav_carries_every_destination() {
        let nav = nav_html(&NavLabels::english(), &Counts::default(), None);
        for needle in [
            "https://docs.opencrabs.com",
            "/#features",
            "/#integrations",
            "/download/",
            "https://github.com/opencrabs/opencrabs",
            "/stats/",
            "class=\"nav-toggle\"",
            "nav-social-link nav-telegram",
            "nav-social-link nav-discord",
        ] {
            assert!(nav.contains(needle), "nav is missing {needle}");
        }
    }

    #[test]
    fn footer_carries_every_destination() {
        let footer = footer_html(&FooterLabels::english(), &Counts::default());
        for needle in [
            "footer-star-cta",
            "footer-callers",
            "href=\"/stats/\"",
            "https://docs.opencrabs.com",
            STORIES_URL,
            "https://github.com/sponsors/adolfousier",
            "https://buymeacoffee.com/opencrabs",
            "footer-comm-popover",
        ] {
            assert!(footer.contains(needle), "footer is missing {needle}");
        }
    }

    #[test]
    fn known_counts_render_and_empty_ones_stay_hidden() {
        let empty = nav_html(&NavLabels::english(), &Counts::default(), None);
        assert!(empty.contains("data-chrome-callers hidden"));
        assert!(!empty.contains("1,465"));

        let full = nav_html(
            &NavLabels::english(),
            &Counts {
                stars: 1234,
                callers: 1465,
            },
            None,
        );
        assert!(full.contains("1,465"));
        assert!(full.contains("★ 1,234"));
        assert!(!full.contains("data-chrome-callers hidden"));
    }

    #[test]
    fn lang_switcher_marks_the_current_locale() {
        let picker = lang_switcher(
            &[("en", "EN", "English"), ("pt-PT", "PT", "Português")],
            "pt-PT",
        );
        assert!(picker.contains(r#"<option value="pt-PT" title="Português" selected>PT</option>"#));
        assert!(picker.contains(r#"<option value="en" title="English">EN</option>"#));
    }

    #[test]
    fn injection_is_idempotent_and_keeps_the_markers() {
        let page = "<body>\n<!-- chrome:nav -->\nold\n<!-- /chrome:nav -->\n<p>hi</p>\n<!-- chrome:footer -->\nold\n<!-- /chrome:footer -->\n</body>";
        let nav = nav_html(&NavLabels::english(), &Counts::default(), None);
        let footer = footer_html(&FooterLabels::english(), &Counts::default());
        let once = inject_page(page, &nav, &footer).expect("inject");
        let twice = inject_page(&once, &nav, &footer).expect("inject again");
        assert_eq!(once, twice);
        assert!(once.contains("class=\"nav-links\""));
        assert!(once.contains("<p>hi</p>"));
    }

    #[test]
    fn missing_marker_is_an_error() {
        assert!(inject_page("<body></body>", "nav", "footer").is_err());
    }
}
