/// Live numbers. A page that already knows them renders them; a page that does
/// not renders the empty slot and `chrome.js` fills it in.
#[derive(Clone, Copy, Debug, Default)]
pub struct Counts {
    pub stars: u32,
    pub callers: u64,
}

/// `1465` -> `1,465`.
pub fn thousands(n: u64) -> String {
    let digits = n.to_string();
    let mut out = String::with_capacity(digits.len() + digits.len() / 3);
    for (i, ch) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i).is_multiple_of(3) {
            out.push(',');
        }
        out.push(ch);
    }
    out
}

/// The language picker. `options` is `(value, label, title)` and `current` is
/// the value that should start selected.
pub fn lang_switcher(options: &[(&str, &str, &str)], current: &str) -> String {
    let mut out = String::from(r#"<select class="lang-switcher" aria-label="Language">"#);
    for (value, label, title) in options {
        let selected = if *value == current { " selected" } else { "" };
        out.push_str(&format!(
            r#"<option value="{value}" title="{title}"{selected}>{label}</option>"#
        ));
    }
    out.push_str("</select>");
    out
}

/// The header. `lang` is the picker markup from [`lang_switcher`] when the page
/// can honour a language change, `None` when it cannot.
