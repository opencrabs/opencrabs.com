//! The site chrome: one header and one footer, rendered by every page.
//!
//! opencrabs.com has four surfaces: the landing SPA at `/`, the static
//! `/download/` page, the `/stats/` dashboard (its own crate) and `404.html`.
//! Before this crate each one carried its own copy of the header and footer,
//! so they drifted: the download page collapsed at a different width, the
//! footer callers pill existed on one page only, and the 404 page had neither.
//!
//! Here the markup is built once, as a string. Any page can embed it: the two
//! Leptos crates put it through `inner_html`, the static pages carry the output
//! between `chrome:nav` / `chrome:footer` markers and are regenerated by the
//! `chrome-static` binary. `chrome.css` and `chrome.js` live beside this file
//! and are what make the markup responsive and alive.
//!
//! The markup is deliberately dependency free. It renders identically in a
//! browser, in a wasm bundle and in a plain `String`, so there is one source of
//! truth rather than one per page.

/// Start of the generated header block in a static page.
pub const NAV_START: &str = "<!-- chrome:nav -->";
/// End of the generated header block in a static page.
pub const NAV_END: &str = "<!-- /chrome:nav -->";
/// Start of the generated footer block in a static page.
pub const FOOTER_START: &str = "<!-- chrome:footer -->";
/// End of the generated footer block in a static page.
pub const FOOTER_END: &str = "<!-- /chrome:footer -->";

