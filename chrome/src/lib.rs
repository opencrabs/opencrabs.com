/// Text for the header. Every field is a finished string, so a page with a
/// locale system passes its own translation and a page without one takes the
/// English default.
#[derive(Clone, Debug)]
pub struct NavLabels {
    pub docs: String,
    pub features: String,
    pub integrations: String,
    pub download: String,
    pub github: String,
    pub callers: String,
    pub or_direct: String,
    /// Where the section links point. The landing links to its own anchors,
    /// every other page has to come back to `/` first.
    pub features_href: String,
    pub integrations_href: String,
}

impl Default for NavLabels {
    fn default() -> Self {
        Self {
            docs: "Docs".into(),
            features: "Features".into(),
            integrations: "Integrations".into(),
            download: "Download".into(),
            github: "GitHub".into(),
            callers: "callers".into(),
            or_direct: "or direct download".into(),
            features_href: "/#features".into(),
            integrations_href: "/#integrations".into(),
        }
    }
}

impl NavLabels {
    pub fn english() -> Self {
        Self::default()
    }

    /// The landing's own section anchors, no round trip to `/`.
    pub fn with_home_anchors(mut self) -> Self {
        self.features_href = "#features".into();
        self.integrations_href = "#integrations".into();
        self
    }
}

